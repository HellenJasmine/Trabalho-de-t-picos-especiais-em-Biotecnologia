"""define a function for encoding:"""

MAX_LENGTH = 128

def encode(docs):
  """
  Tokeniza os textos para entrada no BERT.
  Retorna:
  input_ids: IDs dos tokens
  attention_mask: máscara de atenção
  """

  encoded = tokenizer(
      docs,
      add_special_tokens=True,
      max_length=MAX_LENGTH,
      padding="max_length",
      truncation=True,
      return_attention_mask=True,
      return_tensors="pt"
  )

  return encoded["input_ids"], encoded["attention_mask"]

